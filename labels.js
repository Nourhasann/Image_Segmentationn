// A fixed, deterministic color per class so the same object type always
// gets the same overlay color across runs.
function classColor(classId) {
  const hue = (classId * 37) % 360; // 37 spreads hues out nicely across 80 classes
  return `hsl(${hue}, 70%, 50%)`;
}
